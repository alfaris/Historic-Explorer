// The apps' Kotlin content models (mobile/core-model), generated from the JSON
// Schema of /api/v1/content (contracts/content-v1.schema.json), so they can't
// drift from the TypeScript types. Follows contracts/README.md's decoding rules:
// enums are plain strings (an unknown value is an addition, never an error),
// PeriodEntry is one class with optional `closed` and `days`, IDs and counts are
// Int, other numbers Double, and every optional field defaults to null.

import { readFileSync } from 'node:fs';

export const MODELS_PATH = 'mobile/core-model/src/commonMain/kotlin/io/github/alfaris/walks/model/ContentV1.kt';
const PACKAGE = 'io.github.alfaris.walks.model';

type Schema = {
  type?: string | string[];
  $ref?: string;
  properties?: Record<string, Schema>;
  required?: string[];
  items?: Schema;
  additionalProperties?: boolean | Schema;
  enum?: string[];
  anyOf?: Schema[];
  description?: string;
  const?: unknown;
};

const pascal = (s: string) => s.replace(/(^|[^a-zA-Z0-9])([a-zA-Z0-9])/g, (_m, _p, c: string) => c.toUpperCase());
const constName = (v: string) => v.replace(/([a-z])([A-Z])/g, '$1_$2').replace(/[^a-zA-Z0-9]+/g, '_').toUpperCase();
const doc = (text: string | undefined, indent: string) =>
  text ? `${indent}/** ${text.replace(/\*\//g, '*​/').replace(/\n+/g, ' ')} */\n` : '';

export function kotlinModels(schemaText = readFileSync('contracts/content-v1.schema.json', 'utf8')): string {
  const schema = JSON.parse(schemaText) as { definitions: Record<string, Schema> };
  const defs = schema.definitions;
  const classes: string[] = [];
  const enums: string[] = [];

  const typeOf = (s: Schema, owner: string, prop: string): string => {
    if (s.$ref) {
      const name = s.$ref.replace('#/definitions/', '');
      return defs[name].enum ? 'String' : name;
    }
    if (s.enum) return 'String';
    const types = Array.isArray(s.type) ? s.type.filter(t => t !== 'null') : [s.type];
    const nullable = Array.isArray(s.type) && s.type.includes('null');
    const t = types[0];
    let k: string;
    if (t === 'string') k = 'String';
    else if (t === 'integer') k = 'Int';
    else if (t === 'number') k = 'Double';
    else if (t === 'boolean') k = 'Boolean';
    else if (t === 'array') k = `List<${typeOf(s.items!, owner, prop)}>`;
    else if (t === 'object' && s.additionalProperties && typeof s.additionalProperties === 'object' && !s.properties) {
      k = `Map<String, ${typeOf(s.additionalProperties, owner, prop)}>`;
    } else if (t === 'object' && s.properties) {
      const name = `${owner}${pascal(prop)}`;
      emitClass(name, s);
      k = name;
    } else throw new Error(`Unsupported schema at ${owner}.${prop}: ${JSON.stringify(s).slice(0, 120)}`);
    return nullable ? `${k}?` : k;
  };

  function emitClass(name: string, s: Schema) {
    const required = new Set(s.required ?? []);
    const props = Object.entries(s.properties ?? {}).map(([prop, p]) => {
      const t = typeOf(p, name, prop);
      const optional = !required.has(prop);
      const type = optional && !t.endsWith('?') ? `${t}?` : t;
      return `${doc(p.description, '    ')}    val ${prop}: ${type}${optional || type.endsWith('?') ? ' = null' : ''},`;
    });
    classes.push(`${doc(s.description, '')}@Serializable\ndata class ${name}(\n${props.join('\n')}\n)\n`);
  }

  for (const [name, s] of Object.entries(defs).sort(([a], [b]) => (a < b ? -1 : 1))) {
    if (s.enum) {
      enums.push(
        `${doc(`${s.description ? `${s.description} ` : ''}Known values of a ${name} field, which is a plain String: a value not listed here is a newer one the app doesn't know yet.`, '')}object ${name} {\n${s.enum.map(v => `    const val ${constName(v)} = ${JSON.stringify(v)}`).join('\n')}\n}\n`,
      );
    } else if (s.anyOf) {
      // An untagged union of objects: one class with every member's fields, all optional.
      const merged: Schema = { type: 'object', properties: {}, description: s.description };
      for (const member of s.anyOf) Object.assign(merged.properties!, member.properties);
      emitClass(name, merged);
    } else if (s.type === 'object') emitClass(name, s);
    else throw new Error(`Unsupported definition ${name}`);
  }

  return [
    '// GENERATED by `npm run gen:models` from contracts/content-v1.schema.json. Don\'t edit by hand:',
    '// change the TypeScript types, run `npm run gen:schema`, then `npm run gen:models`.',
    '// Decode with ignoreUnknownKeys = true (see contracts/README.md).',
    '',
    `package ${PACKAGE}`,
    '',
    'import kotlinx.serialization.Serializable',
    '',
    ...enums,
    ...classes,
  ].join('\n');
}
