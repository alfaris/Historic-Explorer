// Prayer-time vectors for the native apps: what the web shows for every Cairo
// day of a few years, from the web's own functions (prayersOn, goldenOn), so an
// app's implementation can be checked against them to the minute.

import { GOLDEN_MINUTES, goldenOn, prayersOn } from '../src/lib/prayer-times.js';

export const PRAYER_VECTORS_PATH = 'contracts/vectors/prayer-times-cairo.json';
export const FIRST_DAY = '2026-01-01';
export const LAST_DAY = '2028-12-31';

/** The fields of each day's row, in order, after the date. */
export const FIELDS = ['fajr', 'sunrise', 'dhuhr', 'asr', 'sunset', 'maghrib', 'isha'] as const;

const MIN = 60_000;
const minutes = (d: Date) => {
  const m = d.getTime() / MIN;
  if (!Number.isInteger(m)) throw new Error(`Not a whole minute: ${d.toISOString()}`);
  return m;
};

/** Noon in Cairo on a calendar day (Cairo is UTC+2 or +3; 10:00 UTC is always that day there). */
const cairoNoon = (day: string) => new Date(`${day}T10:00:00Z`);

export function prayerVectors() {
  const days: (string | number)[][] = [];
  for (let t = Date.parse(`${FIRST_DAY}T00:00:00Z`); t <= Date.parse(`${LAST_DAY}T00:00:00Z`); t += 86_400_000) {
    const day = new Date(t).toISOString().slice(0, 10);
    const at = cairoNoon(day);
    const [fajr, dhuhr, asr, maghrib, isha] = prayersOn(at).map(p => p.at);
    const { morning, evening } = goldenOn(at);
    days.push([day, ...[fajr, morning.start, dhuhr, asr, evening.end, maghrib, isha].map(minutes)]);
  }
  return {
    about:
      'Prayer times and sun times in Cairo as the web computes them (adhan-js, Egyptian General Authority of Survey method). ' +
      'Each row is a Cairo calendar day, then each field as minutes since 1970-01-01T00:00Z. Golden hours are the hour after sunrise and the hour before sunset. ' +
      'Generated by npm run gen:vectors; do not edit by hand.',
    place: { lat: 30.0444, lng: 31.2357 },
    method: 'Egyptian',
    /** The golden hours' length: from sunrise, and up to sunset. */
    goldenMinutes: GOLDEN_MINUTES,
    fields: ['date', ...FIELDS],
    days,
  };
}

export const prayerVectorsText = () => {
  const v = prayerVectors();
  // One day per line, so a diff shows which days changed.
  const rows = v.days.map(d => `    ${JSON.stringify(d)}`).join(',\n');
  const { days: _days, ...head } = v;
  return `${JSON.stringify(head, null, 2).replace(/\n}$/, `,\n  "days": [\n${rows}\n  ]\n}`)}\n`;
};
